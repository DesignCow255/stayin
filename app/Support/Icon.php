    public static function has(string $name): bool
    {
        return isset(self::PATHS[$name]);
    }

    /**
     * Render an inline SVG icon. Unknown names render nothing and are logged in
     * debug so a missing glyph can never silently break a layout contract.
     */
    public static function render(string $name, string $class = '', ?string $label = null, string $stroke = self::DEFAULT_STROKE): string
    {
        if (!self::has($name)) {
            if (\App\Core\Config::bool('app.debug', false)) {
                error_log('[stayin.icon] unknown icon: ' . $name);
            }
            return '';
        }

        $classes = trim('si-icon ' . $class);
        $a11y = $label === null
            ? ' aria-hidden="true" focusable="false"'
            : ' role="img" aria-label="' . htmlspecialchars($label, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '"';

        return '<svg class="' . htmlspecialchars($classes, ENT_QUOTES, 'UTF-8') . '" viewBox="0 0 24 24"'
            . ' width="24" height="24" fill="none" stroke="currentColor" stroke-width="' . $stroke . '"'
            . ' stroke-linecap="round" stroke-linejoin="round"' . $a11y . '>'
            . self::PATHS[$name]
            . '</svg>';
    }

    /**
     * Icon name for an amenity label stored in `properties.amenities`.
     */
    public static function forAmenity(string $amenity): string
    {
        $key = mb_strtolower(trim($amenity));

        return self::AMENITY_ICONS[$key] ?? 'check';
    }

    /**
     * Pretty label for an amenity or enum token, e.g. `guest_house` => `Guest house`.
     */
    public static function label(string $value): string
    {
        return ucfirst(str_replace('_', ' ', trim($value)));
    }

    /**
     * All registered icon names.
     *
     * @return array<int, string>
     */
    public static function names(): array
    {
        return array_keys(self::PATHS);
    }
